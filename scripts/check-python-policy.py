import ast
import io
import json
import re
import sys
import tokenize
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_ROOTS = ("packages", "cli", "plugins/toy", "behavior", "scripts", "tests", "python")
SPDX = {"0BSD", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "MIT", "MPL-2.0", "Unlicense"}
GENERATED_MANIFEST = json.loads((ROOT / "scripts/generated-artifacts.json").read_text(encoding="utf-8"))
GENERATED_FILES = set(GENERATED_MANIFEST["codeArtifacts"])
GENERATED_TYPES = (ROOT / "packages/contracts/generated/types.ts").read_text(encoding="utf-8")
CONTRACT_NAMES = set(re.findall(r"^export type ([A-Za-z_][A-Za-z0-9_]*)", GENERATED_TYPES, re.MULTILINE))
failures = []


def files():
    found = []
    for relative in SOURCE_ROOTS:
        directory = ROOT / relative
        if directory.exists():
            found.extend(path for path in directory.rglob("*.py") if path.is_file() and not {"dist", "build", "node_modules", ".venv", "__pycache__"}.intersection(path.parts))
    return sorted(found)


def line_one_comment(comment):
    parts = comment.split(None, 1)
    return parts[1].strip() if len(parts) == 2 else ""


def inspect(path):
    source = path.read_text(encoding="utf-8")
    relative = path.relative_to(ROOT).as_posix()
    try:
        tree = ast.parse(source, filename=relative)
    except SyntaxError as error:
        failures.append(f"{relative}:{error.lineno}: invalid Python syntax")
        return
    try:
        tokens = tokenize.tokenize(io.BytesIO(source.encode("utf-8")).readline)
        for token in tokens:
            if token.type != tokenize.COMMENT:
                continue
            is_header = token.start[0] == 1 and source[:token.start[1]].strip() == ""
            value = line_one_comment(token.string)
            license_header = is_header and value.startswith("SPDX-License-Identifier:") and value.split(":", 1)[1].strip() in SPDX
            generated_header = is_header and relative in GENERATED_FILES and value == "@generated by scripts/generate-contracts.mjs"
            if not license_header and not generated_header:
                failures.append(f"{relative}:{token.start[0]}: forbidden code comment")
            if any(marker in token.string.lower() for marker in ("todo", "fixme", "workaround")):
                failures.append(f"{relative}:{token.start[0]}: forbidden debt marker")
            if any(marker in token.string.lower() for marker in ("type: ignore", "noqa", "pylint: disable")):
                failures.append(f"{relative}:{token.start[0]}: forbidden lint or type suppression")
    except tokenize.TokenError:
        failures.append(f"{relative}: invalid Python token stream")
    any_aliases = set()
    cast_aliases = set()
    typing_module_aliases = {"typing", "typing_extensions"}
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name in {"typing", "typing_extensions"}:
                    typing_module_aliases.add(alias.asname or alias.name)
        if isinstance(node, ast.ImportFrom) and node.module in {"typing", "typing_extensions"}:
            for alias in node.names:
                if alias.name == "Any":
                    any_aliases.add(alias.asname or alias.name)
                    failures.append(f"{relative}:{node.lineno}: explicit Any is forbidden")
                if alias.name == "cast":
                    cast_aliases.add(alias.asname or alias.name)
    for node in ast.walk(tree):
        if isinstance(node, ast.Name) and node.id in any_aliases | {"Any"}:
            failures.append(f"{relative}:{node.lineno}: explicit Any is forbidden")
        if isinstance(node, ast.Attribute) and node.attr == "Any" and isinstance(node.value, ast.Name) and node.value.id in typing_module_aliases:
            failures.append(f"{relative}:{node.lineno}: explicit Any is forbidden")
        identifier = node.id if isinstance(node, ast.Name) else node.attr if isinstance(node, ast.Attribute) else node.name if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) else ""
        if identifier.lower() in {"todo", "fixme", "workaround"}:
            failures.append(f"{relative}:{node.lineno}: forbidden debt marker identifier {identifier}")
        if isinstance(node, ast.TypeIgnore):
            failures.append(f"{relative}:{node.lineno}: type ignores are forbidden")
        if isinstance(node, ast.Call) and ((isinstance(node.func, ast.Name) and node.func.id in cast_aliases) or (isinstance(node.func, ast.Attribute) and node.func.attr == "cast" and isinstance(node.func.value, ast.Name) and node.func.value.id in typing_module_aliases)):
            failures.append(f"{relative}:{node.lineno}: unchecked casts are forbidden")
        if relative != "python/toy_contracts/generated.py":
            if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) and node.name in CONTRACT_NAMES:
                failures.append(f"{relative}:{node.lineno}: copied contract declaration {node.name}")
            if isinstance(node, (ast.Assign, ast.AnnAssign)):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                for target in targets:
                    names = {child.id for child in ast.walk(target) if isinstance(child, ast.Name)}
                    for name in names.intersection(CONTRACT_NAMES):
                        failures.append(f"{relative}:{node.lineno}: copied contract declaration {name}")


selected = [(ROOT / path).resolve() for path in sys.argv[1:]]
sources = selected or files()
for source in sources:
    inspect(source)

if failures:
    print("\n".join(failures), file=sys.stderr)
    sys.exit(1)
print(f"{len(sources)} Python source files passed comment and type policy")
