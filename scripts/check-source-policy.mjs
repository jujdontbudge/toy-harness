import { readFile, readdir } from "node:fs/promises";
import { extname, relative, resolve } from "node:path";
import ts from "typescript";

const root = resolve(import.meta.dirname, "..");
const sourceRoots = ["packages", "cli", "plugins/toy", "behavior", "scripts", "tests", "python", "swift", "control"];
const sourceExtensions = new Set([".ts", ".tsx", ".mts", ".cts", ".js", ".jsx", ".mjs", ".cjs", ".py", ".swift"]);
const selected = process.argv.slice(2).map((path) => resolve(root, path));
const generatedManifest = JSON.parse(await readFile(resolve(root, "scripts/generated-artifacts.json"), "utf8"));
const generatedFiles = new Set([...generatedManifest.codeArtifacts, ...generatedManifest.deferredCodeArtifacts]);

const walk = async (path) => {
  let entries;
  try {
    entries = await readdir(path, { withFileTypes: true });
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") return [];
    throw error;
  }
  const children = await Promise.all(entries.map(async (entry) => {
    const child = resolve(path, entry.name);
    if (entry.isDirectory()) return ["dist", "node_modules", ".venv", ".git", "__pycache__", "build"].includes(entry.name) ? [] : await walk(child);
    return sourceExtensions.has(extname(entry.name)) ? [child] : [];
  }));
  return children.flat();
};

const files = selected.length > 0
  ? selected
  : (await Promise.all(sourceRoots.map((path) => walk(resolve(root, path)))).then((items) => items.flat()));
const failures = [];
const generatedBanner = /^\s*(?:\/\/|#) @generated by scripts\/generate-contracts\.mjs\s*$/;
const spdxLicense = /^\s*(?:\/\/|#|\/\*|\*|\*\/)?\s*SPDX-License-Identifier:\s*(?:0BSD|Apache-2\.0|BSD-2-Clause|BSD-3-Clause|ISC|MIT|MPL-2\.0|Unlicense)\s*(?:\*\/)?\s*$/;
const debtIdentifier = /^(?:TODO|FIXME|workaround)$/i;

const checkComment = (path, source, start, comment) => {
  const prefix = source.slice(0, start);
  const atHeader = prefix.replace(/^\uFEFF/, "").trim().length === 0;
  const relativePath = relative(root, path).replaceAll("\\", "/");
  const isBanner = atHeader && generatedFiles.has(relativePath) && generatedBanner.test(comment);
  const isLicense = atHeader && spdxLicense.test(comment);
  if (!isBanner && !isLicense) {
    failures.push(`${relativePath}: forbidden code comment`);
  }
  if (/\b(?:TODO|FIXME|workaround)\b/i.test(comment)) {
    failures.push(`${relativePath}: forbidden debt marker`);
  }
  if (/@(?:ts-ignore|ts-expect-error|ts-nocheck)|eslint-disable|\bnoqa\b|type:\s*ignore/i.test(comment)) {
    failures.push(`${relativePath}: forbidden lint or type suppression`);
  }
};

const tsSourcePolicy = (source, path) => {
  const extension = extname(path);
  const scriptKind = extension === ".tsx" ? ts.ScriptKind.TSX : extension === ".jsx" ? ts.ScriptKind.JSX : [".js", ".mjs", ".cjs"].includes(extension) ? ts.ScriptKind.JS : ts.ScriptKind.TS;
  const sourceFile = ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true, scriptKind);
  const ranges = new Set();
  const checkRanges = (items) => {
    if (!items) return;
    for (const range of items) {
      const key = `${range.pos}:${range.end}`;
      if (ranges.has(key)) continue;
      ranges.add(key);
      checkComment(path, source, range.pos, source.slice(range.pos, range.end));
    }
  };
  const relativePath = relative(root, path).replaceAll("\\", "/");
  const visit = (node) => {
    checkRanges(ts.getLeadingCommentRanges(source, node.getFullStart()));
    checkRanges(ts.getTrailingCommentRanges(source, node.end));
    if (ts.isIdentifier(node)) {
      if (debtIdentifier.test(node.text)) failures.push(`${relativePath}: forbidden debt marker identifier ${node.text}`);
    }
    if (node.kind === ts.SyntaxKind.AnyKeyword) failures.push(`${relativePath}: explicit any type is forbidden`);
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
};

const swiftComments = (source, path) => {
  let index = 0;
  let depth = 0;
  let commentStart = -1;
  let commentEnd = -1;
  while (index < source.length) {
    if (depth > 0) {
      if (source.startsWith("/*", index)) {
        depth += 1;
        index += 2;
      } else if (source.startsWith("*/", index)) {
        depth -= 1;
        index += 2;
        if (depth === 0) checkComment(path, source, commentStart, source.slice(commentStart, index));
      } else {
        index += 1;
      }
      continue;
    }
    if (source.startsWith("//", index)) {
      commentStart = index;
      const end = source.indexOf("\n", index);
      commentEnd = end < 0 ? source.length : end;
      checkComment(path, source, commentStart, source.slice(commentStart, commentEnd));
      index = commentEnd;
      continue;
    }
    if (source.startsWith("/*", index)) {
      commentStart = index;
      depth = 1;
      index += 2;
      continue;
    }
    let rawHashes = 0;
    while (source[index + rawHashes] === "#") rawHashes += 1;
    const quoteIndex = index + rawHashes;
    if (source[quoteIndex] === '"') {
      const triple = source.startsWith('"""', quoteIndex);
      const openingWidth = rawHashes + (triple ? 3 : 1);
      const closing = `${triple ? '"""' : '"'}${"#".repeat(rawHashes)}`;
      index += openingWidth;
      while (index < source.length) {
        if (source.startsWith(closing, index) && (rawHashes > 0 || source[index - 1] !== "\\")) {
          index += closing.length;
          break;
        }
        index += 1;
      }
      continue;
    }
    if (/[A-Za-z_]/.test(source[index] ?? "")) {
      const start = index;
      index += 1;
      while (/[A-Za-z0-9_]/.test(source[index] ?? "")) index += 1;
      const identifier = source.slice(start, index);
      const relativePath = relative(root, path).replaceAll("\\", "/");
      if (debtIdentifier.test(identifier)) failures.push(`${relativePath}: forbidden debt marker identifier ${identifier}`);
      continue;
    }
    index += 1;
  }
  if (depth > 0) failures.push(`${relative(root, path)}: unterminated block comment`);
};

for (const path of files) {
  const source = await readFile(path, "utf8");
  const extension = extname(path);
  const relativePath = relative(root, path).replaceAll("\\", "/");
  if ([".js", ".jsx", ".mjs", ".cjs"].includes(extension) && !relativePath.startsWith("scripts/") && relativePath !== "eslint.config.mjs") {
    failures.push(`${relativePath}: Toy product code must use strict TypeScript, not JavaScript`);
  }
  if (extension === ".py") continue;
  if (extension === ".swift") {
    swiftComments(source, path);
  } else if (extension !== ".py") {
    tsSourcePolicy(source, path);
  }
}

if (failures.length > 0) {
  process.stderr.write(`${failures.join("\n")}\n`);
  process.exitCode = 1;
} else {
  process.stdout.write(`${files.length} source files passed comment and debt policy\n`);
}
